package collections;

// Interface for demonstrating Set collection operations.
public interface ISetDemonstrator {
    
    // Demonstrates HashSet operations.
    void demonstrateHashSet();
    
    // Demonstrates LinkedHashSet operations.
    void demonstrateLinkedHashSet();
    
    // Demonstrates TreeSet operations.
    void demonstrateTreeSet();
    
    // Demonstrates set operations: union, intersection, difference.
    void demonstrateSetOperations();
    
    //Demonstrates working with User objects in a Set.
    void demonstrateUserSet();
    
    // Demonstrates basic Set operations.
    void demonstrateBasicSetOperations();
    
    //Demonstrates working with User class in HashSet.
    void demonstrateUserClassWithHashSet();
    
    //Runs all Set demonstrations.
    void demonstrateAll();
}


